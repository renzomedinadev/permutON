create or replace function public.validate_publication_state()
returns trigger language plpgsql security definer set search_path = '' as $$
begin
 if TG_OP = 'INSERT' and (NEW.province_id is null or NEW.locality_id is null) then
  raise exception 'Seleccioná provincia y localidad de Argentina.';
 end if;
 if NEW.status='active' and exists (select 1 from public.offers o where o.publication_id=NEW.id and o.status='accepted') then
  raise exception 'Esta publicación ya tiene una permuta aceptada y no puede reactivarse.';
 end if;
 return NEW;
end;
$$;
create trigger validate_publication_state before insert or update on public.publications
 for each row execute function public.validate_publication_state();

-- Serializa la creación de ofertas con su aceptación y comprueba que siga activa.
create or replace function public.validate_offer_publication()
returns trigger language plpgsql security definer set search_path = '' as $$
declare p public.publications;
begin
 select * into p from public.publications where id=NEW.publication_id for update;
 if not found or p.status<>'active' then raise exception 'La publicación ya no está disponible para permutar.'; end if;
 if NEW.status<>'pending' then raise exception 'La propuesta debe comenzar pendiente.'; end if;
 return NEW;
end;
$$;
create trigger validate_offer_publication before insert on public.offers
 for each row execute function public.validate_offer_publication();

create or replace function public.change_offer_status(offer_id uuid,new_status text)
returns text language plpgsql security definer set search_path = '' as $$
declare selected_offer public.offers; p public.publications; target_publication uuid;
begin
 if auth.uid() is null then raise exception 'Ingresá a tu cuenta.'; end if;
 if new_status is null or new_status not in ('accepted','rejected','cancelled') then raise exception 'Estado inválido.'; end if;
 select publication_id into target_publication from public.offers where id=offer_id;
 if not found then raise exception 'La propuesta ya no existe.'; end if;
 -- Siempre bloquear publicación primero para evitar aceptaciones simultáneas.
 select * into p from public.publications where id=target_publication for update;
 if not found then raise exception 'La publicación ya no existe.'; end if;
 select * into selected_offer from public.offers where id=offer_id for update;
 if not found then raise exception 'La propuesta ya no existe.'; end if;
 if not ((new_status in ('accepted','rejected') and p.owner_id=auth.uid())
 or (new_status='cancelled' and selected_offer.sender_id=auth.uid())) then raise exception 'No tenés permiso para esta acción.'; end if;
 if selected_offer.status<>'pending' then raise exception 'La propuesta ya fue resuelta. Actualizá la lista.'; end if;
 if new_status='accepted' and p.status<>'active' then raise exception 'La publicación ya no está activa.'; end if;
 update public.offers set status=new_status,updated_at=now() where id=offer_id;
 if new_status='accepted' then
  update public.publications set status='reserved' where id=p.id;
  update public.offers set status='rejected',updated_at=now() where publication_id=p.id and id<>offer_id and status='pending';
 end if;
 return new_status;
end;
$$;
-- Aplicar la nueva regla también a las propuestas aceptadas previamente.
update public.publications p set status='reserved' where p.status='active'
 and exists (select 1 from public.offers o where o.publication_id=p.id and o.status='accepted');
update public.offers o set status='rejected',updated_at=now() where o.status='pending'
 and exists(select 1 from public.offers a where a.publication_id=o.publication_id and a.status='accepted');
revoke all on function public.validate_publication_state() from public,anon,authenticated;
revoke all on function public.validate_offer_publication() from public,anon,authenticated;
commit;
